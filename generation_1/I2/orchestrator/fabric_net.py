#!/usr/bin/env python3
"""
Fabric orchestrator — the CU (control unit) loop of the Moore-style fabric.

DATA PLANE:  N cloned Lancius verifier ALUs executed by the real C runtime
             (lancius run), dispatched over the ALU bus, aggregated.
CONTROL      one small external LLM (Ollama, qwen2.5-coder:3b) that does NOT
PLANE:       see the problem, does NOT compute — it translates the aggregated
             verdict packet into one sentence of English.

Derivation rows are generated by the same gen1 machinery as run_big.py
(algos + verifier5 + training normalization), so this is the same distribution
the pool's weights were fitted on.
"""
import os, sys, json, random, urllib.request

_sd = os.path.dirname(os.path.abspath(__file__))
while not os.path.isfile(os.path.join(_sd, 'paths.py')):
    _n = os.path.dirname(_sd)
    assert _n != _sd, 'paths.py not found above %s' % __file__
    _sd = _n
sys.path.insert(0, _sd)
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
import paths as _paths
_paths.enforce()
REPO = _paths.REPO
ALU_POOL = _paths.ALU_POOL
DATA_DIR = _paths.DATA_DIR

from algos import ALGORITHMS
from algos_gen1_ext import EXT_ALGOS
from algos_gen1_big import EXT2_ALGOS
import verifier5 as V
import bench_gen1 as B
import bus as FABRIC
import isa as LAIS

ALL100 = list(ALGORITHMS) + list(EXT_ALGOS) + list(EXT2_ALGOS)
DATA_DIR = DATA_DIR
CU_MODEL = "qwen2.5-coder:3b"
N_ALU = 4

def init_axes():
    d0 = B.parse_lancius(FABRIC.load_pool(ALU_POOL, 1)[0])
    nodes = d0["nodes"] if isinstance(d0, dict) and "nodes" in d0 else d0
    shapes = {tuple(n["shape"][:n["ndim"]]) for n in nodes if n.get("has_w")}
    B.H1G = [s[1] for s in shapes if len(s) == 2 and s[0] == 65][0]
    B.H2G = [s[0] for s in shapes if len(s) == 2 and s[1] == 5][0]
    return B.compute_musd(DATA_DIR)

def make_row(seed, mu, sd, master):
    """One gen1 derivation row -> (normalized features, label_idx, meta)."""
    rng = B.PyRng(seed)
    k = master.randrange(len(ALL100))
    algo = ALL100[k]
    params0, _ = algo.build(rng)
    params = dict(params0)
    level = master.choice(B.LEVELS)
    steps = algo._steps(params)
    if not steps:
        return None
    rep, stc, kind = V.make_candidate(algo, params, steps, rng, level)
    chk = V.check(algo, params, steps, rep, stc)
    f = V.row_features(algo, chk, -1)
    x = (f - mu) / sd
    return dict(feats=x, label=B.LEVELS.index(level), level=level,
                algo=algo.name, kind=kind)

def cu_explain(packet, n_predict=80):
    """CONTROL PLANE: external LLM turns the packet into one English sentence."""
    sys_msg = ("You are the control unit of a computation fabric. Lancius ALUs "
               "verified a math derivation and output a verdict packet. "
               "Class 4 = accept (+1.0), 3 = accept (stretched +0.5), "
               "2 = neutral (0.0), 1 = doubt (-0.5), 0 = reject (-1.0). "
               "Report exactly one short sentence in English. No preamble.")
    prompt = ("verdict packet:\n\n%s\n\nOne short sentence about the verdict." %
              json.dumps(packet, sort_keys=True))
    body = json.dumps({"model": CU_MODEL, "system": sys_msg, "prompt": prompt,
                       "stream": False, "raw": False,
                       "options": {"num_predict": n_predict, "temperature": 0.2}}).encode()
    req = urllib.request.Request("http://127.0.0.1:11434/api/generate", data=body,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=120) as r:
        out = json.loads(r.read().decode()).get("response", "").strip()
    s = out.replace("\n", " ").strip()
    if s and s[-1] not in ".!?\"'": s += "."
    return s

def derive_and_verdict(seed, mu, sd, master, pool, n_alu=N_ALU):
    row = None
    for _ in range(8):
        row = make_row(seed, mu, sd, master)
        if row: break
        master.advance()
    if not row:
        return None
    vs = FABRIC.dispatch(pool[:n_alu], row["feats"])
    agg = FABRIC.aggregate(vs, strategy="mean")
    conf = LAIS.packet_confidence(agg)
    pkt = {"row": seed, "algo": row["algo"], "kind": row["kind"],
           "aggregate": dict(agg), "confidence": conf}
    cu_line = cu_explain(pkt)
    match = (agg.argmax >= 0 and agg.argmax == row["label"])
    return row, vs, agg, conf, cu_line, match

def run_demo(n_rows, n_alu=N_ALU, master_seed='at-random'):
    mu, sd = init_axes()
    pool = FABRIC.load_pool(ALU_POOL, n_alu)
    master = random.Random(master_seed if isinstance(master_seed, int)
                           else random.randrange(2**30))
    print("== Moore fabric: %d Lancius ALUs + CU %s ==" % (n_alu, CU_MODEL))
    ok = tot = 0
    for i in range(n_rows):
        seed = random.randrange(2**30)
        out = derive_and_verdict(seed, mu, sd, master, pool, n_alu)
        if not out: continue
        row, vs, agg, conf, cu_line, match = out
        tot += 1
        ok += bool(match)
        truth = B.LVLNAME[row["level"]]
        print("\n[%d] derive: %s" % (i, row["algo"]))
        print("    VERDICT  alus ->", [v.argmax for v in vs])
        print("    AGGREGATE (%s) argmax=%d margin=%.3f" %
              (agg.strategy, agg.argmax, agg.margin))
        print("    CONFIDENCE margin=%.3f span=%.3f" % (conf["margin"], conf["uniform"]))
        print("    TRUTH: class %s" % truth)
        print("    MATCH: %s" % ("YES" if match else "NO"))
        print("    CU: %s" % cu_line)
    print("\ndemo accuracy: %d/%d" % (ok, tot) if tot else "no rows")

if __name__ == "__main__":
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 6
    na = int(sys.argv[2]) if len(sys.argv) > 2 else N_ALU
    run_demo(n, na)
